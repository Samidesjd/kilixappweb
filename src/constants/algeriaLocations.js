function transliterateArabicLocation(value, language) {
  if (!value || /[A-Za-z]/.test(value) && !/[\u0600-\u06FF]/.test(value)) return String(value);
  const known = COMMON_LOCATION_WORDS.find(([ar]) => ar === value);
  if (known) return known[1];
  const table = language === 'fr' ? ARABIC_LATIN_FR : ARABIC_LATIN_EN;
  return String(value)
    .split('')
    .map(ch => table[ch] ?? ch)
    .join('')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/\bAl\s+/g, 'El ');
}

export function getLocalizedLocationName(value, language = 'ar') {
  if (language === 'ar') return value;
  return transliterateArabicLocation(value, language);
}

